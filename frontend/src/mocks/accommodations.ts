function city(name: string, code: string): PlaceRef {
  return { type: 'city', id: `city-${code}`, name, code };
}

interface StayDraft {
  id: string;
  name: string;
  type: AccommodationOffer['type'];
  destination: PlaceRef;
  country: string;
  countryCode: string;
  regionIds: string[];
  imageIndex: number;
  rating: number;
  reviewCount: number;
  price: number;
  currency?: CurrencyCode;
  amenities: Amenity[];
  breakfastIncluded: boolean;
  freeCancellation: boolean;
  privateBathroom: boolean;
  distanceFromCenterKm: number;
  roomsAvailable: number;
  provider: string;
  partnerId: string;
  recommendedRank: number;
}

function stay(draft: StayDraft): AccommodationOffer {
  const pricePerNight = money(draft.price, draft.currency ?? 'EUR');
  return {
    id: draft.id,
    name: draft.name,
    type: draft.type,
    destination: draft.destination,
    country: draft.country,
    countryCode: draft.countryCode,
    regionIds: draft.regionIds,
    imageUrl:
      IMAGES[draft.imageIndex] ??
      'https://images.unsplash.com/photo-1566073771259-6a8506099945?w=960&auto=format&fit=crop',
    imageAlt: draft.name,
    rating: draft.rating,
    reviewCount: draft.reviewCount,
    pricePerNight,
    amenities: draft.amenities,
    breakfastIncluded: draft.breakfastIncluded,
    freeCancellation: draft.freeCancellation,
    privateBathroom: draft.privateBathroom,
    distanceFromCenterKm: draft.distanceFromCenterKm,
    roomsAvailable: draft.roomsAvailable,
    provider: draft.provider,
    mealPlan: draft.breakfastIncluded ? 'breakfast' : 'room_only',
    recommendedRank: draft.recommendedRank,
    bookingOptions: [
      {
        partnerId: draft.partnerId,
        partnerName: draft.provider,
        price: pricePerNight,
        deeplink: `https://example.com/${draft.partnerId}/${draft.id}`,
      },
    ],
  };
}

